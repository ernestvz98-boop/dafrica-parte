-- Supabase SIMULADO para probar migraciones en un Postgres local (nunca en producción):
-- roles de la API, auth.uid() y tiene_permiso() leídos de variables de la sesión, almacén vacío y
-- las tablas existentes de la cola y del registro (mismo esquema que producción, sin datos).
do $$ begin
  if not exists (select 1 from pg_roles where rolname='anon') then create role anon nologin; end if;
  if not exists (select 1 from pg_roles where rolname='authenticated') then create role authenticated nologin; end if;
  if not exists (select 1 from pg_roles where rolname='service_role') then create role service_role nologin bypassrls; end if;
end $$;
create schema auth; create schema storage;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('prueba.uid', true), '')::uuid $$;
create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
create table storage.objects (id uuid primary key default gen_random_uuid(), bucket_id text, name text);
alter table storage.objects enable row level security;
create function public.tiene_permiso(permiso_codigo text) returns boolean language sql stable as $$
  select (','||coalesce(current_setting('prueba.permisos', true),'')||',') like ('%,'||permiso_codigo||',%') $$;
grant usage on schema public, auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
create table public.stel_sync_log (
  id bigint generated by default as identity primary key, iniciado_en timestamptz not null default now(), finalizado_en timestamptz,
  tipo_sync text not null, estado text not null default 'INICIADO', registros_leidos integer not null default 0,
  registros_creados integer not null default 0, registros_actualizados integer not null default 0, error text, detalle jsonb);
alter table public.stel_sync_log enable row level security;
create policy stel_sync_log_select on public.stel_sync_log for select to authenticated using (public.tiene_permiso('costes.ver'));
-- Los privilegios por defecto de Supabase (también TRUNCATE para los roles de la API).
grant select, truncate, references, trigger on public.stel_sync_log to authenticated;
grant truncate, references, trigger on public.stel_sync_log to anon;
